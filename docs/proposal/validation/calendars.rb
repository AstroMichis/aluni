# frozen_string_literal: true

# Builds config/crops/planting_calendars.yml (read by Crops::PlantingCalendar) from USDA NASS weekly
# crop progress ("PCT PLANTED"), so the app plants a crop in the month farmers in that state really
# plant it rather than in the FAO-56 table's row (corn: 1 April). The hindcast found the FAO-56 month
# 4-7 weeks early for Iowa corn (docs/proposal/validation, studies V7 and V8).
#
# For each state, crop and year it interpolates the dates the state reached 10%, 50% and 90% planted,
# then keeps the median of the last YEARS years. The planting month is the month of the median 50% date.
#
# Input: data/nass/progress_all.json (every state, fetch.rb --only=nass_progress_all) when present,
# else data/nass/progress.json (Iowa only).
# Run: mise exec -- ruby docs/proposal/validation/calendars.rb

require "date"
require "json"
require "yaml"

# Progress files from any site folder (fetch.rb writes data/<site>/nass/); the all-states file wins.
DATA = File.expand_path("data", __dir__)
OUT = File.expand_path("../../../config/crops/planting_calendars.yml", __dir__)
YEARS = 10
# NASS commodity (and class, when it matters) => catalog key (config/crops/agronomy.yml).
CROPS = {
  [ "CORN", nil ] => "zea-mays", [ "SOYBEANS", nil ] => "glycine-max", [ "SORGHUM", nil ] => "sorghum-bicolor",
  [ "SUNFLOWER", nil ] => "helianthus-annuus", [ "OATS", nil ] => "avena-sativa", [ "BARLEY", nil ] => "hordeum-vulgare",
  [ "WHEAT", "SPRING, (EXCL DURUM)" ] => "triticum-aestivum", [ "COTTON", nil ] => "gossypium-hirsutum",
  [ "PEANUTS", nil ] => "arachis-hypogaea", [ "RICE", nil ] => "oryza-sativa", [ "SUGARBEETS", nil ] => "beta-vulgaris",
  [ "DRY EDIBLE BEANS", nil ] => "phaseolus-vulgaris", [ "POTATOES", nil ] => "solanum-tuberosum"
}.freeze

file = (Dir[File.join(DATA, "*/nass/progress_all.json")] + Dir[File.join(DATA, "*/nass/progress.json")]).first or abort "no NASS progress file (run fetch.rb)"
rows = JSON.parse(File.read(file)).select { |r| r["unit_desc"] == "PCT PLANTED" && r["week_ending"].to_s =~ /\A\d{4}-\d{2}-\d{2}/ }

# The date a cumulative weekly series first reaches `pct`, linearly between the two weeks around it.
def reach(points, pct)
  points.each_cons(2) do |(d0, v0), (d1, v1)|
    return d0 if v0 >= pct
    return d0 + ((d1 - d0) * (pct - v0) / (v1 - v0).to_f).round if v1 >= pct && v1 > v0
  end
  points.last && points.last.last >= pct ? points.last.first : nil
end

def median(dates_as_yday) = dates_as_yday.sort[dates_as_yday.size / 2]

calendar = Hash.new { |h, k| h[k] = {} }
rows.group_by { |r| [ r["state_name"], r["commodity_desc"], r["class_desc"] ] }.each do |(state, commodity, klass), list|
  key = CROPS[[ commodity, klass ]] || CROPS[[ commodity, nil ]]
  next unless key
  next if commodity == "WHEAT" && klass != "SPRING, (EXCL DURUM)"

  by_year = list.group_by { |r| r["year"].to_i }.select { |y, _| y < Date.today.year }
  recent = by_year.keys.sort.last(YEARS)
  marks = recent.filter_map do |y|
    points = by_year[y].map { |r| [ Date.parse(r["week_ending"]), Float(r["Value"].to_s.delete(","), exception: false).to_f ] }.sort
    p10, p50, p90 = [ 10, 50, 90 ].map { |pct| reach(points, pct) }
    [ p10, p50, p90 ].all? ? [ p10.yday, p50.yday, p90.yday ] : nil
  end
  next if marks.size < 5

  to_md = ->(yday) { Date.ordinal(2001, yday).strftime("%m-%d") }
  start, middle, finish = (0..2).map { |i| median(marks.map { |m| m[i] }) }
  calendar[state.downcase.split.map(&:capitalize).join(" ")][key] = {
    "planting_month" => Date.ordinal(2001, middle).month,
    "planted_10" => to_md.(start), "planted_50" => to_md.(middle), "planted_90" => to_md.(finish),
    "years" => "#{recent.first}-#{recent.last}"
  }
end

header = <<~YAML
  # Regional planting calendars, read by Crops::PlantingCalendar. Generated by
  # docs/proposal/validation/calendars.rb from USDA NASS weekly crop progress
  # (median date each state reached 10, 50 and 90 % planted over the years shown).
  # Do not edit by hand: rerun the script. Keyed by ISO country code, then the
  # state or region name as Farm#admin_area stores it, then the catalog crop key.
YAML
File.write(OUT, header + { "US" => calendar.sort.to_h }.to_yaml.sub(/\A---\n/, ""))
puts "Wrote #{OUT}: #{calendar.size} states, #{calendar.values.sum(&:size)} crop calendars from #{File.basename(file)}"
calendar.sort.first(3).each { |state, crops| crops.each { |k, v| puts "  #{state} #{k}: 50% planted #{v['planted_50']} (month #{v['planting_month']}), 10-90% #{v['planted_10']} to #{v['planted_90']}" } }
